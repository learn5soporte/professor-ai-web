/**
 * Interpolación mínima para strings del diccionario con placeholders
 * `{clave}` (ej. "Reto {n} de {total}"). Se mantiene deliberadamente simple:
 * reemplazo literal, sin formateo ni pluralización.
 */
export function tpl(
  texto: string,
  vars: Record<string, string | number>
): string {
  return texto.replace(/\{(\w+)\}/g, (m, clave) =>
    clave in vars ? String(vars[clave]) : m
  );
}
